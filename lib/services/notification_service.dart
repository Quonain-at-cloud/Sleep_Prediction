import 'package:flutter_local_notifications/flutter_local_notifications.dart';
import 'package:permission_handler/permission_handler.dart';

/// A singleton service that wraps the [flutter_local_notifications] plugin and
/// provides a simple API for showing local notifications on both Android and iOS.
///
/// This does *not* rely on Firebase Cloud Messaging. It only shows *local* push
/// notifications once your Flutter code receives the payload (e.g. via
/// WebSocket). Therefore it perfectly fits use-cases where your backend already
/// pushes data in real-time using Socket.IO, SSE, etc. and you simply need to
/// surface those messages as OS-level notifications.
class NotificationService {
  NotificationService._internal();

  static final NotificationService _instance = NotificationService._internal();

  factory NotificationService() => _instance;

  final FlutterLocalNotificationsPlugin _flutterLocalNotificationsPlugin =
      FlutterLocalNotificationsPlugin();

  bool _initialized = false;

  /// Call this once (e.g. in main.dart) before using [showNotification].
  Future<void> init() async {
    if (_initialized) return;

    // Android setup
    const AndroidInitializationSettings androidInitSettings =
        AndroidInitializationSettings('@mipmap/ic_launcher');

    // iOS setup
    const DarwinInitializationSettings iosInitSettings =
        DarwinInitializationSettings(
      requestAlertPermission: true,
      requestBadgePermission: true,
      requestSoundPermission: true,
    );

    final InitializationSettings initSettings = InitializationSettings(
      android: androidInitSettings,
      iOS: iosInitSettings,
    );

    await _flutterLocalNotificationsPlugin.initialize(initSettings);

    // Request runtime notification permission on Android 13+
    if (await Permission.notification.isDenied) {
      await Permission.notification.request();
    }
    _initialized = true;
  }

  /// Display a simple notification containing a [title] and [body].
  Future<void> show({required String title, required String body}) async {
    if (!_initialized) await init();

    const AndroidNotificationDetails androidDetails = AndroidNotificationDetails(
      'sleep_prediction_channel', // channel ID
      'Sleep Prediction Notifications', // channel name visible to user
      channelDescription:
          'Notifications generated by the Sleep Prediction application',
      importance: Importance.max,
      priority: Priority.high,
    );

    const NotificationDetails notificationDetails =
        NotificationDetails(android: androidDetails);

    await _flutterLocalNotificationsPlugin.show(
      DateTime.now().millisecondsSinceEpoch.remainder(100000),
      title,
      body,
      notificationDetails,
    );
  }
}
